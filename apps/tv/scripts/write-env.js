/**
 * Writes src/env.generated.ts from environment variables at build time, so
 * `POSTERS=off npm run build:debug` and `RECCO_API_BASE=... npm run build:debug`
 * work without code changes. Runs before every build and after install.
 */
const fs = require('fs');
const path = require('path');

const apiBase = process.env.RECCO_API_BASE || 'http://10.0.2.2:8787';
// Debug builds post focus/events here (pnpm dev:local prints them). Defaults to the API.
const debugBase = process.env.RECCO_DEBUG_BASE || apiBase;
const posters = (process.env.POSTERS || 'on').toLowerCase() !== 'off';

const out = `// Generated by scripts/write-env.js. Do not edit.
export const ENV = {
  apiBase: ${JSON.stringify(apiBase)},
  posters: ${posters},
  debugBase: ${JSON.stringify(debugBase)},
} as const;
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'env.generated.ts'), out);
console.log(`[recco] apiBase=${apiBase} debugBase=${debugBase} posters=${posters ? 'on' : 'off'}`);
